export function getSectorDefinition(sectorId: string): SectorDefinition {
  const match = SECTOR_CATALOG.find(s => s.id === sectorId || s.name_en.toLowerCase().includes(sectorId.toLowerCase()));
  return match || SECTOR_CATALOG[0];
}

export function getDepartmentDocumentsForSector(sectorId: string): Record<Department, DepartmentDocumentRequirement[]> {
  const normalizedId = (sectorId || 'manufacturing_engineering') as SectorId;
  const docs = DEPARTMENT_DOCUMENT_REQUIREMENTS.filter(doc => {
    if (doc.sector_ids === 'all') return true;
    return doc.sector_ids.includes(normalizedId);
  });

  const result: Record<Department, DepartmentDocumentRequirement[]> = {
    industries: [],
    mpcb: [],
    fire: [],
    labour: []
  };

  for (const doc of docs) {
    result[doc.department].push(doc);
  }

  return result;
}
